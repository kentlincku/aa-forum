//! `aaf service install|uninstall|status`：開機（登入）自動啟動。
//! macOS 寫 LaunchAgent（`~/Library/LaunchAgents/io.aaf.<name>.plist`），Linux 寫 systemd user unit
//! （`~/.config/systemd/user/aaf-<name>.service`）。只動自己產生的檔（有 [`MARKER`]）；
//! 手寫的 unit 不接管，`start`／`stop` 靠 INVOCATION_ID＋MainPID 認得它。

use crate::service::{self, Manager};
use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};
use std::time::Duration;

const MARKER: &str = "generated by aaf service install";

pub struct InstallOpts {
    pub listen: Option<String>,
    pub name: Option<String>,
    pub force: bool,
    pub no_start: bool,
    pub timeout: Duration,
    pub allow_protected: bool,
}

/// macOS 的隱私保護（TCC）資料夾：launchd 啟動的程式讀這些地方會卡住等授權（實測卡在 dyld 開啟執行檔）。
fn protected_dirs() -> Vec<PathBuf> {
    let Some(h) = std::env::var_os("HOME").map(PathBuf::from) else {
        return Vec::new();
    };
    [
        "Desktop",
        "Documents",
        "Downloads",
        "Library/Mobile Documents",
    ]
    .iter()
    .map(|d| h.join(d))
    .chain([PathBuf::from("/Volumes")])
    .collect()
}

fn protected(p: &Path) -> Option<PathBuf> {
    protected_dirs().into_iter().find(|d| p.starts_with(d))
}

/// roles.json 裡提到的受保護路徑（agent 的工作目錄等）。
fn protected_in_roles(home: &Path) -> Vec<String> {
    let Ok(text) = std::fs::read_to_string(home.join("deploy/roles.json")) else {
        return Vec::new();
    };
    let mut hits: Vec<String> = protected_dirs()
        .iter()
        .map(|d| d.to_string_lossy().into_owned())
        .filter(|d| text.contains(d.as_str()))
        .collect();
    hits.dedup();
    hits
}

/// 服務名稱：預設是 home 目錄名；只留英數與 `.-_`，其他字元換成 `-`。
fn service_name(home: &Path, name: Option<&str>) -> Result<String> {
    let raw = match name {
        Some(n) => n.to_string(),
        None => home
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .context("cannot derive a service name from the home path; pass --name")?,
    };
    let n: String = raw
        .trim()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || matches!(c, '.' | '-' | '_') {
                c
            } else {
                '-'
            }
        })
        .collect();
    let n = n.trim_matches(|c| matches!(c, '.' | '-')).to_string();
    if n.is_empty() {
        bail!("invalid service name {raw:?}; pass --name");
    }
    Ok(n)
}

/// 這個 OS 上要寫的檔：管理者、路徑。
struct Target {
    manager: Manager,
    path: PathBuf,
}

fn target(name: &str) -> Result<Target> {
    let home_dir = PathBuf::from(std::env::var_os("HOME").context("HOME is not set")?);
    if cfg!(target_os = "macos") {
        let label = format!("io.aaf.{name}");
        Ok(Target {
            path: home_dir
                .join("Library/LaunchAgents")
                .join(format!("{label}.plist")),
            manager: Manager::Launchd(label),
        })
    } else if cfg!(target_os = "linux") {
        let unit = format!("aaf-{name}.service");
        let dir = std::env::var_os("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|| home_dir.join(".config"))
            .join("systemd/user");
        Ok(Target {
            path: dir.join(&unit),
            manager: Manager::SystemdUser(unit),
        })
    } else {
        bail!("aaf service supports macOS (launchd) and Linux (systemd) only")
    }
}

fn manager_tag(m: &Manager) -> String {
    match m {
        Manager::Launchd(l) => format!("launchd:{l}"),
        Manager::SystemdUser(u) => format!("systemd:{u}"),
        Manager::SystemdSystem(u) => format!("systemd-system:{u}"),
    }
}

fn generated(path: &Path) -> bool {
    std::fs::read_to_string(path).is_ok_and(|s| s.contains(MARKER))
}

fn xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

struct Spec<'a> {
    exe: &'a Path,
    home: &'a Path,
    listen: &'a str,
    path_env: &'a str,
    tag: &'a str,
}

fn plist(label: &str, s: &Spec) -> String {
    let log = s.home.join("var").join(service::LOG);
    let args = [
        s.exe.to_string_lossy().into_owned(),
        "--home".into(),
        s.home.to_string_lossy().into_owned(),
        "up".into(),
        "--listen".into(),
        s.listen.into(),
    ]
    .iter()
    .map(|a| format!("\t\t<string>{}</string>\n", xml(a)))
    .collect::<String>();
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- {MARKER}: change it with `aaf service install`, remove it with `aaf service uninstall` -->
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>{label}</string>
	<key>ProgramArguments</key>
	<array>
{args}	</array>
	<key>WorkingDirectory</key>
	<string>{home}</string>
	<key>EnvironmentVariables</key>
	<dict>
		<key>PATH</key>
		<string>{path}</string>
		<key>AAF_SERVICE</key>
		<string>{tag}</string>
	</dict>
	<key>RunAtLoad</key>
	<true/>
	<key>KeepAlive</key>
	<dict>
		<key>SuccessfulExit</key>
		<false/>
	</dict>
	<key>ThrottleInterval</key>
	<integer>10</integer>
	<key>ExitTimeOut</key>
	<integer>30</integer>
	<key>StandardOutPath</key>
	<string>{log}</string>
	<key>StandardErrorPath</key>
	<string>{log}</string>
</dict>
</plist>
"#,
        label = xml(label),
        home = xml(&s.home.to_string_lossy()),
        path = xml(s.path_env),
        tag = xml(s.tag),
        log = xml(&log.to_string_lossy()),
    )
}

/// systemd 的引號字串：`\` 與 `"` 跳脫，`%` 寫成 `%%`（specifier）。
fn sd_quote(s: &str) -> String {
    format!(
        "\"{}\"",
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    )
}

/// ExecStart 的參數另外會展開 `$VAR`：`$` 寫成 `$$`（Environment= 不展開，不用）。
fn sd_arg(s: &str) -> String {
    sd_quote(&s.replace('$', "$$"))
}

fn unit(s: &Spec) -> Result<String> {
    // StandardOutput=append: 與 WorkingDirectory 不能加引號：路徑有空白或控制字元就不支援
    let home = s.home.to_string_lossy();
    if home.chars().any(|c| c.is_whitespace() || c.is_control()) {
        bail!(
            "the home path contains whitespace, which systemd cannot use for the log path: {home}"
        );
    }
    let home_sd = home.replace('%', "%%");
    let log = format!("{home_sd}/var/{}", service::LOG);
    Ok(format!(
        "# {MARKER}: change it with `aaf service install`, remove it with `aaf service uninstall`
[Unit]
Description=AA Forum ({home_sd})

[Service]
Type=simple
ExecStart={exe} --home {home_q} up --listen {listen}
WorkingDirectory={home_sd}
Environment={path} {tag}
Restart=on-failure
RestartSec=5
KillMode=mixed
TimeoutStopSec=30
StandardOutput=append:{log}
StandardError=append:{log}

[Install]
WantedBy=default.target
",
        exe = sd_arg(&s.exe.to_string_lossy()),
        home_q = sd_arg(&home),
        listen = sd_arg(s.listen),
        path = sd_quote(&format!("PATH={}", s.path_env)),
        tag = sd_quote(&format!("AAF_SERVICE={}", s.tag)),
    ))
}

fn write_atomic(path: &Path, body: &str) -> Result<()> {
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
    }
    let tmp = path.with_extension("aaf-tmp");
    std::fs::write(&tmp, body)?;
    std::fs::rename(&tmp, path)?;
    Ok(())
}

fn launchd_loaded(label: &str) -> bool {
    service::quiet(&["launchctl", "print", &Manager::launchd_target(label)])
}

/// 已載入就 bootout，並等 launchd 真的卸下（太快 bootstrap 會失敗：Input/output error）。
async fn bootout(label: &str) -> Result<()> {
    if !launchd_loaded(label) {
        return Ok(());
    }
    service::run(&["launchctl", "bootout", &Manager::launchd_target(label)])?;
    for _ in 0..100 {
        if !launchd_loaded(label) {
            return Ok(());
        }
        tokio::time::sleep(Duration::from_millis(100)).await;
    }
    bail!("launchd still has {label} loaded 10s after bootout")
}

/// systemd 找到的同名 unit 檔（FragmentPath；沒有回 None）。
fn systemd_fragment(unit: &str) -> Option<PathBuf> {
    let out = std::process::Command::new("systemctl")
        .args(["--user", "show", "-p", "FragmentPath", "--value", unit])
        .stderr(std::process::Stdio::null())
        .output()
        .ok()
        .filter(|o| o.status.success())?;
    let p = String::from_utf8_lossy(&out.stdout).trim().to_string();
    (!p.is_empty()).then(|| PathBuf::from(p))
}

fn gui_domain() -> String {
    format!("gui/{}", nix::unistd::getuid())
}

pub async fn install(home: &Path, o: &InstallOpts) -> Result<i32> {
    let home = service::absolute(home)?;
    let name = service_name(&home, o.name.as_deref())?;
    let t = target(&name)?;
    let tag = manager_tag(&t.manager);
    if let Some(r) = service::running(&home) {
        if r.info.as_ref().and_then(|i| i.managed_by.as_deref()) == Some(tag.as_str()) {
            bail!(
                "already installed and running as {} (pid {}); to change it, run `aaf service uninstall` first",
                t.manager.describe(),
                r.pid
            );
        }
        bail!(
            "aaf is running for this home (pid {}); stop it first (`aaf --home {} stop`, which waits for idle turns), then install",
            r.pid,
            home.display()
        );
    }
    // 一個 home 只能有一個管理者：別的名稱（--name 換過）或手寫的 unit 還裝著就拒絕，否則開機後兩個搶鎖、無限重啟
    let other = service::installed_service(&home)
        .into_iter()
        .chain(
            service::read_run_info(&home)
                .and_then(|i| i.managed_by)
                .as_deref()
                .and_then(Manager::parse)
                .filter(Manager::installed),
        )
        .find(|m| *m != t.manager);
    if let Some(m) = other {
        bail!(
            "this home is already managed by {}; remove or disable that first (`aaf service uninstall --name <old>` for one aaf installed, or disable a hand-written unit yourself)",
            m.describe()
        );
    }
    // systemd：同名 unit 可能在別的目錄（/etc/systemd/user、~/.local/share/systemd/user）
    if let Manager::SystemdUser(unit) = &t.manager {
        if let Some(frag) = systemd_fragment(unit).filter(|f| *f != t.path) {
            if !o.force {
                bail!(
                    "a unit named {unit} already exists at {}; pass --force to shadow it with {}",
                    frag.display(),
                    t.path.display()
                );
            }
        }
    }
    if t.path.exists() && !generated(&t.path) {
        if !o.force {
            bail!(
                "{} exists and was not written by aaf service install; pass --force to replace it (a backup is kept)",
                t.path.display()
            );
        }
        // 備份放在 instance 的 var/（留在 LaunchAgents 會被 launchd 當成另一個同名 job）
        let bak = home.join("var").join(format!(
            "{}.bak-{}",
            t.path
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default(),
            chrono_stamp()
        ));
        std::fs::copy(&t.path, &bak)?;
        eprintln!("backed up {} to {}", t.path.display(), bak.display());
    }
    let listen = o
        .listen
        .clone()
        .or_else(|| service::read_run_info(&home).map(|i| i.listen))
        .unwrap_or_else(|| service::DEFAULT_LISTEN.into());
    let exe = std::fs::canonicalize(std::env::current_exe()?)?;
    if cfg!(target_os = "macos") {
        for (what, p) in [("the aaf executable", &exe), ("the instance home", &home)] {
            if let Some(d) = protected(p) {
                if !o.allow_protected {
                    bail!(
                        "{what} is under {}, which macOS protects: a launchd service hangs there waiting for permission.\n\
                         Install aaf outside it (for example `cargo install --path apps/aaf`, which puts it in ~/.cargo/bin) and run that copy's\n\
                         `aaf service install`, or give aaf Full Disk Access in System Settings and pass --allow-protected.",
                        d.display()
                    );
                }
                eprintln!(
                    "warning: {what} is under {} (allowed with --allow-protected)",
                    d.display()
                );
            }
        }
        let hits = protected_in_roles(&home);
        if !hits.is_empty() {
            eprintln!(
                "warning: deploy/roles.json refers to {}; agents started by the launchd service need Full Disk Access\n\
                 for aaf to work there (System Settings → Privacy & Security), or they will hang.",
                hits.join(", ")
            );
        }
    }
    // 服務管理器的 PATH 很短：用安裝當下的 PATH，agent 才找得到 node、claude、codex 等程式
    let path_env = std::env::var("PATH").unwrap_or_else(|_| "/usr/bin:/bin".into());
    let spec = Spec {
        exe: &exe,
        home: &home,
        listen: &listen,
        path_env: &path_env,
        tag: &tag,
    };
    let body = match &t.manager {
        Manager::Launchd(label) => plist(label, &spec),
        _ => unit(&spec)?,
    };
    // 舊的（同名、aaf 產生的）若已載入，先卸下再換檔
    if let Manager::Launchd(label) = &t.manager {
        bootout(label).await?;
    }
    write_atomic(&t.path, &body)?;
    // start／stop 依這個紀錄轉交（實例還沒成功起來、run.json 沒記到管理者時也要認得）
    std::fs::write(
        home.join("var").join(service::SERVICE_FILE),
        format!("{tag}\n"),
    )?;
    println!("wrote {}", t.path.display());
    match &t.manager {
        Manager::Launchd(_) if o.no_start => {
            println!(
                "installed; it starts at the next login (or now with `aaf --home {} start`)",
                home.display()
            );
            return Ok(0);
        }
        Manager::Launchd(_) => {
            // RunAtLoad：載入即啟動
            service::run(&[
                "launchctl",
                "bootstrap",
                &gui_domain(),
                &t.path.to_string_lossy(),
            ])?;
        }
        Manager::SystemdUser(unit) => {
            service::run(&["systemctl", "--user", "daemon-reload"])?;
            if o.no_start {
                service::run(&["systemctl", "--user", "enable", unit])?;
            } else {
                service::run(&["systemctl", "--user", "enable", "--now", unit])?;
            }
            linger_hint();
            if o.no_start {
                println!(
                    "installed; it starts at the next login (or now with `aaf --home {} start`)",
                    home.display()
                );
                return Ok(0);
            }
        }
        Manager::SystemdSystem(_) => unreachable!(),
    }
    let ready = service::wait_ready(&home, None, None, o.timeout).await?;
    let code = service::report_ready(&home, ready, o.timeout)?;
    if code == 0 {
        match service::running(&home).and_then(|r| r.info).and_then(|i| i.managed_by) {
            Some(m) if m == tag => println!("managed by {}", t.manager.describe()),
            other => eprintln!(
                "warning: the service started but records manager {other:?}, expected {tag}; check `aaf service status`"
            ),
        }
    }
    Ok(code)
}

/// 登出後還要繼續跑需要 linger（系統設定，只提示不代跑）。
fn linger_hint() {
    let user = std::env::var("USER").unwrap_or_default();
    let out = std::process::Command::new("loginctl")
        .args(["show-user", &user, "-p", "Linger", "--value"])
        .output();
    let linger = out
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim() == "yes");
    if linger != Some(true) {
        println!(
            "note: without lingering the service stops when you log out and starts at your next login.\n      To keep it running across logouts and reboots: sudo loginctl enable-linger {user}"
        );
    }
}

fn chrono_stamp() -> String {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs().to_string())
        .unwrap_or_default()
}

pub async fn uninstall(home: &Path, name: Option<&str>, stop: &service::StopOpts) -> Result<i32> {
    let home = service::absolute(home)?;
    let name = service_name(&home, name)?;
    let t = target(&name)?;
    if !t.path.exists() {
        println!("not installed ({} does not exist)", t.path.display());
        return Ok(0);
    }
    if !generated(&t.path) {
        bail!(
            "{} was not written by aaf service install; remove it yourself",
            t.path.display()
        );
    }
    let tag = manager_tag(&t.manager);
    let r = service::running(&home);
    // 是不是這個服務的實例：run.json 記的管理者，或管理器回報的主程序就是它（up 時沒驗證到也算）
    let main = t.manager.main_pid();
    let ours = r.as_ref().is_some_and(|r| {
        r.info.as_ref().and_then(|i| i.managed_by.as_deref()) == Some(tag.as_str())
            || main == Some(r.pid)
    });
    if let (Some(r), true) = (&r, ours) {
        if let Some(code) = service::refuse_if_busy(&home, r, stop).await? {
            return Ok(code);
        }
    }
    match &t.manager {
        Manager::Launchd(label) => bootout(label).await?,
        Manager::SystemdUser(unit) => {
            service::run(&["systemctl", "--user", "disable", "--now", unit])?;
        }
        Manager::SystemdSystem(_) => unreachable!(),
    }
    if ours && !service::wait_released(&home, stop.timeout).await {
        eprintln!(
            "still stopping after {}s; the file is kept. Check `aaf status`",
            stop.timeout.as_secs()
        );
        return Ok(1);
    }
    std::fs::remove_file(&t.path)?;
    let _ = std::fs::remove_file(home.join("var").join(service::SERVICE_FILE));
    if matches!(t.manager, Manager::SystemdUser(_)) {
        service::run(&["systemctl", "--user", "daemon-reload"])?;
    }
    if ours {
        service::reap(&home).await?;
    }
    println!("removed {}", t.path.display());
    if let Some(r) = service::running(&home) {
        println!(
            "note: aaf is still running for this home outside the service manager (pid {})",
            r.pid
        );
    } else if ours {
        println!(
            "stopped; start it again with `aaf --home {} start`",
            home.display()
        );
    }
    Ok(0)
}

pub fn status(home: &Path, name: Option<&str>) -> Result<i32> {
    let home = std::fs::canonicalize(home).unwrap_or_else(|_| home.to_path_buf());
    let name = service_name(&home, name)?;
    let t = target(&name)?;
    println!("{}  {}", t.manager.describe(), t.path.display());
    if !t.path.exists() {
        println!("  installed  no");
        return Ok(3);
    }
    println!(
        "  installed  yes{}",
        if generated(&t.path) {
            ""
        } else {
            " (not written by aaf service install)"
        }
    );
    let main = t.manager.main_pid();
    println!(
        "  running    {}",
        main.map(|p| format!("pid {p}")).unwrap_or("no".into())
    );
    match service::running(&home) {
        Some(r) if Some(r.pid) == main => println!("  instance   pid {} (this service)", r.pid),
        Some(r) => println!(
            "  instance   pid {} is running outside this service ({})",
            r.pid,
            r.info
                .and_then(|i| i.managed_by)
                .unwrap_or("aaf start or aaf up".into())
        ),
        None => println!("  instance   not running"),
    }
    Ok(if main.is_some() { 0 } else { 3 })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec<'a>(exe: &'a Path, home: &'a Path) -> Spec<'a> {
        Spec {
            exe,
            home,
            listen: "127.0.0.1:8121",
            path_env: "/opt/homebrew/bin:/usr/bin:/x$y",
            tag: "x",
        }
    }

    #[test]
    fn names() {
        assert_eq!(
            service_name(Path::new("/Users/me/aaf-alice"), None).unwrap(),
            "aaf-alice"
        );
        assert_eq!(
            service_name(Path::new("/x/My AAF"), None).unwrap(),
            "My-AAF"
        );
        assert_eq!(service_name(Path::new("/x"), Some("work")).unwrap(), "work");
        assert!(service_name(Path::new("/x"), Some("///")).is_err());
    }

    #[test]
    fn plist_escapes_and_marks() {
        let (exe, home) = (Path::new("/a&b/aaf"), Path::new("/Users/me/aaf-alice"));
        let p = plist("io.aaf.aaf-alice", &spec(exe, home));
        assert!(p.contains(MARKER));
        assert!(p.contains("<string>/a&amp;b/aaf</string>"));
        assert!(p.contains("<string>/Users/me/aaf-alice/var/aaf-up.log</string>"));
        assert!(p.contains("<key>SuccessfulExit</key>\n\t\t<false/>"));
        assert!(p.contains("<string>127.0.0.1:8121</string>"));
    }

    #[test]
    fn unit_quotes_and_marks() {
        let (exe, home) = (Path::new("/opt/a b/a$x"), Path::new("/home/me/aaf-100%"));
        let u = unit(&spec(exe, home)).unwrap();
        assert!(u.starts_with("# generated by aaf service install"));
        assert!(u.contains("ExecStart=\"/opt/a b/a$$x\" --home \"/home/me/aaf-100%%\" up --listen \"127.0.0.1:8121\""));
        assert!(u.contains("StandardOutput=append:/home/me/aaf-100%%/var/aaf-up.log"));
        assert!(
            u.contains("Environment=\"PATH=/opt/homebrew/bin:/usr/bin:/x$y\" \"AAF_SERVICE=x\"")
        );
        assert!(u.contains("KillMode=mixed"));
        assert!(unit(&spec(exe, Path::new("/home/me/my aaf"))).is_err());
    }
}
